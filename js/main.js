const themeToggle = document.querySelector(".theme-toggle");
const prefersDark = window.matchMedia("(prefers-color-scheme: dark)");
const languageButtons = document.querySelectorAll(".language-button");
const emailMenu = document.querySelector("[data-email-menu]");
const emailTrigger = document.querySelector("[data-email-trigger]");
const emailPopover = document.querySelector("[data-email-popover]");
const emailCopyButton = document.querySelector("[data-email-copy]");
const emailFeedback = document.querySelector("[data-email-feedback]");
const profileChat = document.querySelector("[data-profile-chat]");
const chatPanel = document.querySelector("[data-profile-chat-panel]");
const chatToggle = document.querySelector("[data-chat-toggle]");
const chatClose = document.querySelector("[data-chat-close]");
const chatMessages = document.querySelector("[data-chat-messages]");
const chatQuestions = document.querySelector("[data-chat-questions]");
const chatTopics = [
  { question: "chat-question-role", answer: "chat-answer-role" },
  { question: "chat-question-expertise", answer: "chat-answer-expertise" },
  { question: "chat-question-projects", answer: "chat-answer-projects" },
  { question: "chat-question-contact", answer: "chat-answer-contact" },
];
const chatHistory = [];
let currentLanguage = "es";

function translatePage(language) {
  const copy = translations[language];
  currentLanguage = language;
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (key in copy) element.textContent = copy[key];
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    const key = element.dataset.i18nContent;
    if (key in copy) element.setAttribute("content", copy[key]);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (key in copy) element.setAttribute("aria-label", copy[key]);
  });

  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    const key = element.dataset.i18nTitle;
    if (key in copy) element.setAttribute("title", copy[key]);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (key in copy) element.setAttribute("alt", copy[key]);
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.language === language;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  updateThemeLabel();
  renderChat();
  if (emailFeedback) emailFeedback.textContent = "";
  saveLanguage(language);
}

function saveLanguage(language) {
  try {
    localStorage.setItem("lang", language);
  } catch (error) {
    console.error("Could not save the language preference.", error);
  }
}

function updateThemeLabel() {
  if (!themeToggle) return;
  const key = document.documentElement.dataset.theme === "dark" ? "theme-light-label" : "theme-dark-label";
  themeToggle.setAttribute("aria-label", translations[currentLanguage][key]);
  themeToggle.title = translations[currentLanguage][key];
}

function setTheme(theme) {
  document.documentElement.dataset.theme = theme;
  updateThemeLabel();
}

function fallbackCopy(value) {
  const textArea = document.createElement("textarea");
  textArea.value = value;
  textArea.setAttribute("readonly", "");
  textArea.style.position = "fixed";
  textArea.style.opacity = "0";
  textArea.style.pointerEvents = "none";
  document.body.appendChild(textArea);
  textArea.select();

  let copied = false;
  try {
    copied = document.execCommand("copy");
  } finally {
    textArea.remove();
  }
  return copied;
}

function setEmailMenuOpen(open) {
  if (!emailPopover || !emailTrigger || !emailMenu) return;
  emailPopover.hidden = !open;
  emailTrigger.setAttribute("aria-expanded", String(open));
  emailMenu.classList.toggle("is-open", open);
}

function renderChat() {
  if (!chatMessages || !chatQuestions) return;
  const copy = translations[currentLanguage];
  chatMessages.replaceChildren();

  const greeting = document.createElement("p");
  greeting.className = "profile-chat__message profile-chat__message--assistant";
  greeting.textContent = copy["chat-greeting"];
  chatMessages.appendChild(greeting);

  chatHistory.forEach(({ question, answer }) => {
    const userMessage = document.createElement("p");
    userMessage.className = "profile-chat__message profile-chat__message--user";
    userMessage.textContent = copy[question];
    chatMessages.appendChild(userMessage);

    const assistantMessage = document.createElement("div");
    assistantMessage.className = "profile-chat__message profile-chat__message--assistant";
    assistantMessage.textContent = copy[answer];
    if (answer === "chat-answer-contact") {
      const emailLink = document.createElement("a");
      emailLink.className = "profile-chat__contact-link";
      emailLink.href = "mailto:emilioego@hotmail.com";
      emailLink.textContent = copy["chat-contact-email"];
      assistantMessage.appendChild(emailLink);

      const linkedinLink = document.createElement("a");
      linkedinLink.className = "profile-chat__contact-link";
      linkedinLink.href = "https://www.linkedin.com/in/emilioego";
      linkedinLink.target = "_blank";
      linkedinLink.rel = "noopener noreferrer";
      linkedinLink.textContent = copy["chat-contact-linkedin"];
      assistantMessage.appendChild(linkedinLink);
    }
    chatMessages.appendChild(assistantMessage);
  });

  chatQuestions.replaceChildren();
  chatTopics.forEach(({ question, answer }) => {
    const button = document.createElement("button");
    button.className = "profile-chat__question";
    button.type = "button";
    button.dataset.chatQuestion = question;
    button.dataset.chatAnswer = answer;
    button.textContent = copy[question];
    chatQuestions.appendChild(button);
  });
}

function setChatOpen(open) {
  if (!chatPanel || !chatToggle) return;
  chatPanel.hidden = !open;
  chatToggle.setAttribute("aria-expanded", String(open));
  profileChat?.classList.toggle("is-open", open);
  if (open) {
    chatQuestions?.querySelector("button")?.focus();
  } else {
    chatToggle.focus();
  }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const language = button.dataset.language;
    if (language === "en" || language === "es") translatePage(language);
  });
});

themeToggle?.addEventListener("click", () => {
  setTheme(document.documentElement.dataset.theme === "dark" ? "light" : "dark");
});

emailTrigger?.addEventListener("click", () => {
  setEmailMenuOpen(emailTrigger.getAttribute("aria-expanded") !== "true");
});

chatToggle?.addEventListener("click", () => {
  setChatOpen(chatToggle.getAttribute("aria-expanded") !== "true");
});

chatClose?.addEventListener("click", () => {
  setChatOpen(false);
});

chatQuestions?.addEventListener("click", (event) => {
  if (!(event.target instanceof Element)) return;
  const button = event.target.closest("[data-chat-question]");
  if (!(button instanceof HTMLButtonElement)) return;
  const question = button.dataset.chatQuestion;
  const answer = button.dataset.chatAnswer;
  if (!question || !answer) return;

  chatHistory.push({ question, answer });
  if (chatHistory.length > 6) chatHistory.shift();
  renderChat();
  chatMessages?.scrollTo({ top: chatMessages.scrollHeight, behavior: "smooth" });
  chatQuestions?.querySelector("button")?.focus();
});

emailCopyButton?.addEventListener("click", async () => {
  if (!emailMenu || !emailFeedback) return;
  const email = emailMenu.dataset.email;
  if (!email) {
    emailFeedback.textContent = translations[currentLanguage]["email-copy-error"];
    return;
  }

  let copied = false;
  if (navigator.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(email);
      copied = true;
    } catch (error) {
      console.warn("Clipboard API failed; trying the browser fallback.", error);
    }
  }

  if (!copied) {
    try {
      copied = fallbackCopy(email);
    } catch (error) {
      console.error("Could not copy the email address.", error);
    }
  }

  emailFeedback.textContent = translations[currentLanguage][copied ? "email-copied" : "email-copy-error"];
});

document.addEventListener("click", (event) => {
  if (emailMenu && event.target instanceof Node && !emailMenu.contains(event.target)) {
    setEmailMenuOpen(false);
  }
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && emailTrigger?.getAttribute("aria-expanded") === "true") {
    setEmailMenuOpen(false);
    emailTrigger.focus();
  }
  if (event.key === "Escape" && chatToggle?.getAttribute("aria-expanded") === "true") {
    setChatOpen(false);
  }
});

renderChat();
if (profileChat) profileChat.hidden = false;

let initialLanguage = "es";
try {
  const storedLanguage = localStorage.getItem("lang");
  if (storedLanguage === "en" || storedLanguage === "es") initialLanguage = storedLanguage;
} catch (error) {
  console.error("Could not read the saved language preference.", error);
}

translatePage(initialLanguage);
setTheme(prefersDark.matches ? "dark" : "light");
